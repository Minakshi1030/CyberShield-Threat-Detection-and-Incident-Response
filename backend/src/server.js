require("dotenv").config();
const express=require("express"), cors=require("cors"), helmet=require("helmet"), morgan=require("morgan"), rateLimit=require("express-rate-limit");
const connectDB=require("./config/db");
const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL||"http://localhost:5173"}));
app.use(express.json({limit:"1mb"}));
app.use(morgan("dev"));
app.use("/api/auth",rateLimit({windowMs:15*60*1000,max:100}));
app.get("/api/health",(req,res)=>res.json({status:"ok",service:"CyberShield API",time:new Date().toISOString()}));
app.use("/api/auth",require("./routes/auth"));
app.use("/api/logs",require("./routes/logs"));
app.use("/api/alerts",require("./routes/alerts"));
app.use("/api/incidents",require("./routes/incidents"));
app.use("/api/rules",require("./routes/rules"));
app.use("/api/analytics",require("./routes/analytics"));
app.use("/api/reports",require("./routes/reports"));
app.use("/api/simulation",require("./routes/simulation"));
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:"Internal server error"});});
const PORT=process.env.PORT||5001;
connectDB().then(()=>app.listen(PORT,()=>console.log(`CyberShield API running on http://localhost:${PORT}`))).catch(e=>{console.error("Database connection failed:",e.message);process.exit(1);});
